// The genus-7 population of the tables of [Sto19]: 1000 distinct h drawn uniformly from
//   { h in Z[x] : deg h <= 7, |coefficients| <= 10, h(0) odd, h(1) even,
//     positive leading coefficient }
// by rejection sampling with a recorded seed, written to genus7_h.txt in the order drawn
// (coefficients from the constant term up). run_table.m reads the curves from that file, so
// the table can be reproduced without this script. Run from this directory:
//   magma -b make_genus7.m < /dev/null
// Optional parameters: seed (default 20261115), count (default 1000), out (default genus7_h.txt).

SetColumns(0);
if not assigned seed then seed := "20261115"; end if;
if not assigned count then count := "1000"; end if;
if not assigned out then out := "genus7_h.txt"; end if;
seed := StringToInteger(seed); count := StringToInteger(count);
g := 7; b := 10;

SetSeed(seed);
// h(0) is drawn from the odd numbers in [-b, b], the other coefficients from [-b, b];
// a draw is rejected if h(1) is odd, the leading coefficient is negative, or h was drawn before.
odd := [c : c in [-b..b] | IsOdd(c)];
seen := {};
hs := [];
draws := 0;
while #hs lt count do
  draws +:= 1;
  c := [Random(odd)] cat [Random(-b, b) : j in [1..g]];
  lc := [a : a in c | a ne 0][#[a : a in c | a ne 0]]; // h(0) is odd, so c has a nonzero entry
  if IsEven(&+c) and lc gt 0 and c notin seen then
    Include(~seen, c);
    Append(~hs, c);
  end if;
end while;

mv1, mv2, mv3 := GetVersion();
F := Open(out, "w");
fprintf F, "# Genus-7 population of the tables of [Sto19]: %o distinct h, drawn uniformly from\n",
        count;
fprintf F, "# {deg h <= 7, |coefficients| <= 10, h(0) odd, h(1) even, leading coefficient > 0}.\n";
fprintf F, "# Generated by make_genus7.m with SetSeed(%o) in Magma V%o.%o-%o (%o draws).\n",
        seed, mv1, mv2, mv3, draws;
fprintf F, "# One h per line, coefficients from the constant term up to x^7, in the order drawn.\n";
for c in hs do
  fprintf F, "%o\n", Join([Sprint(a) : a in c], ",");
end for;
delete F;
printf "%o polynomials written to %o (%o draws, seed %o)\n", #hs, out, draws, seed;
quit;
